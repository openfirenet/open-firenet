#!/usr/bin/env python3
"""Builds open-firenet/firenet_display_logo.h: the logo of the small screen of boards that have one (160x80).

The emblem and the two words are stored as 8-bit coverage masks (anti-aliased); the firmware colours them at run time,
so the emblem and "Firenet" can shift between yellow and dark orange. Run it after changing the emblem; the header is
checked in. `--preview DIR` writes a few frames as PNG to look at the animation without a board.
"""
import sys, pathlib
from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
EMBLEM = ROOT / "assets" / "brand-icon@2x.png"
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
W, H = 160, 80
EM = 62                      # emblem size on the screen
BG = (12, 15, 23)            # page background #0c0f17
# colour ramp of the animation, from yellow to dark orange (the logo is amber -> orange-red)
RAMP = [(253, 224, 71), (247, 168, 28), (249, 115, 22), (194, 65, 12)]

def emblem_mask():
    """The emblem file is orange line art on a dark rounded tile: the red channel is the coverage of the lines."""
    im = Image.open(EMBLEM).convert("RGBA")
    m = im.width // 8
    im = im.crop((m, m, im.width - m, im.height - m))   # leave out the edge of the tile
    r = im.split()[0].point(lambda v: max(0, min(255, (v - 20) * 255 // 215)))
    box = r.point(lambda v: 255 if v > 60 else 0).getbbox()
    r = r.crop(box)
    k = EM / max(r.size)
    return r.resize((max(1, round(r.width * k)), max(1, round(r.height * k))), Image.LANCZOS)

def word(txt, size):
    f = ImageFont.truetype(FONT, size)
    l, t, r, b = f.getbbox(txt)
    im = Image.new("L", ((r - l) * 4, (b - t) * 4), 0)
    ImageDraw.Draw(im).text((-l * 4, -t * 4), txt, font=ImageFont.truetype(FONT, size * 4), fill=255)
    return im.resize((r - l, b - t), Image.LANCZOS)

def layers():
    em = emblem_mask()
    open_m, fire_m = word("Open", 19), word("Firenet", 19)
    x0 = EM + 13            # room between the emblem and the words
    gap = 6
    total = open_m.height + gap + fire_m.height
    y0 = (H - total) // 2
    return [("emblem", 3 + (EM - em.width) // 2, (H - em.height) // 2, em),
            ("open", x0, y0, open_m),
            ("firenet", x0, y0 + open_m.height + gap, fire_m)]

def write_header(path):
    L = layers()
    out = ["// Generated by tools/gen_display_logo.py: do not edit.",
           "// Anti-aliased coverage masks of the logo for the 160x80 screen; the firmware colours them.",
           "#pragma once", "#include <cstdint>", "namespace firenet { namespace logo {",
           f"constexpr int SCREEN_W = {W}, SCREEN_H = {H};",
           "struct Layer { int16_t x, y, w, h; const uint8_t* mask; };"]
    for name, x, y, m in L:
        data = list(m.getdata())
        out.append(f"static const uint8_t {name.upper()}_MASK[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(str(v) for v in data[i:i + 24]) + ",")
        out.append("};")
    for name, x, y, m in L:
        out.append(f"constexpr Layer {name.upper()} = {{ {x}, {y}, {m.width}, {m.height}, {name.upper()}_MASK }};")
    out.append("}}  // namespace firenet::logo")
    pathlib.Path(path).write_text("\n".join(out) + "\n")

def ramp(p):
    """p in 0..1 along RAMP."""
    p = max(0.0, min(1.0, p)) * (len(RAMP) - 1)
    i = min(int(p), len(RAMP) - 2); f = p - i
    a, b = RAMP[i], RAMP[i + 1]
    return tuple(round(a[k] + (b[k] - a[k]) * f) for k in range(3))

def frame(t):
    """t in 0..1: the colour wave rises through the flame and travels along the word."""
    img = Image.new("RGB", (W, H), BG)
    import math
    for name, x, y, m in layers():
        px = img.load()
        for j in range(m.height):
            for i in range(m.width):
                a = m.getpixel((i, j))
                if not a:
                    continue
                if name == "open":
                    col = (241, 245, 249)
                else:
                    pos = (1 - j / m.height) if name == "emblem" else i / m.width
                    ph = 0.5 + 0.5 * math.sin(2 * math.pi * (t - pos * 0.6))
                    col = ramp(ph)
                bgc = px[x + i, y + j]
                px[x + i, y + j] = tuple((col[k] * a + bgc[k] * (255 - a)) // 255 for k in range(3))
    return img

if __name__ == "__main__":
    if "--preview" in sys.argv:
        d = pathlib.Path(sys.argv[sys.argv.index("--preview") + 1]); d.mkdir(parents=True, exist_ok=True)
        fr = [frame(k / 6) for k in range(6)]
        sheet = Image.new("RGB", (W * 3 * 2, H * 2 * 2), BG)
        for k, f in enumerate(fr):
            sheet.paste(f.resize((W * 2, H * 2), Image.NEAREST), ((k % 3) * W * 2, (k // 3) * H * 2))
        sheet.save(d / "logo_frames.png")
    else:
        write_header(ROOT / "open-firenet" / "firenet_display_logo.h")
