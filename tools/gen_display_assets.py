#!/usr/bin/env python3
"""Builds open-firenet/firenet_display_assets.h: the fonts and icons of the small screen (160x80).

Everything is an 8-bit anti-aliased coverage mask that the firmware colours at run time: two fonts cut from DejaVu Sans
Bold (a big one for the figures, a small one for captions) and a few Lucide icons (ISC licence, as on the page and in the
installer). Run it after changing the lists below; the header is checked in.
"""
import os, pathlib, subprocess, tempfile
from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
# The icons come from the installer's lucide-static package (npm install there); LUCIDE_ICONS overrides the folder.
LUCIDE = pathlib.Path(os.environ.get("LUCIDE_ICONS", ROOT.parent.parent / "open-firenet-installer" / "node_modules" / "lucide-static" / "icons"))
FIRST, LAST = 32, 255
BIG_PX, MED_PX, SMALL_PX, ADDR_PX = 34, 22, 13, 14      # ADDR: the IP address, as large as fits beside an icon
LATIN = set("àâäçéèêëîïôöùûüÀÂÄÇÉÈÊËÎÏÔÖÙÛÜßìòÌÒ")   # the accents of the screen languages (French, Italian, German); every other character above 127 stays empty
BIG_CHARS = set("0123456789.,-+°%:/ ")      # the figures only; the rest of the big font stays empty
ICON_PX = 34
ICONS = ["flame", "thermometer", "zap", "gauge", "wifi", "wifi-off", "plug-zap", "triangle-alert", "circle-alert",
         "lock-open", "unplug", "power", "package", "refresh-cw", "house", "timer"]

def glyphs(px, chars=None):
    big = 4
    f = ImageFont.truetype(FONT, px * big)
    asc, desc = ImageFont.truetype(FONT, px).getmetrics()
    out = []
    for cp in range(FIRST, LAST + 1):
        ch = chr(cp)
        if cp > 127 and ch not in LATIN: out.append((0, 0, 0, 0, round(f.getlength(" ") / big), b"")); continue
        if cp == 127: ch = "→"               # DEL slot: the arrow, written "\x7f" in the screen text
        if cp == 126: ch = "°"               # the screen text writes "~" for the degree sign
        if chars is not None and ch not in chars:
            out.append((0, 0, 0, 0, round(f.getlength(" ") / big), b"")); continue
        adv = round(f.getlength(ch) / big)
        l, t, r, b = f.getbbox(ch)
        if r <= l or b <= t:
            out.append((0, 0, 0, 0, adv, b"")); continue
        im = Image.new("L", (r - l, b - t), 0)
        ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255)
        x0, y0 = l // big, t // big                      # whole-pixel position of the box
        w, h = -(-(r - l) // big), -(-(b - t) // big)
        im = im.resize((w * big, h * big)) if False else im
        canvas = Image.new("L", (w * big, h * big), 0); canvas.paste(im, (l - x0 * big, t - y0 * big))
        g = canvas.resize((w, h), Image.LANCZOS)
        out.append((w, h, x0, y0, adv, bytes(g.getdata())))
    return out, asc + desc, asc

def icon_mask(name):
    svg = (LUCIDE / f"{name}.svg").read_text().replace("currentColor", "#ffffff")
    with tempfile.TemporaryDirectory() as d:
        s = pathlib.Path(d) / "i.svg"; s.write_text(svg)
        png = pathlib.Path(d) / "i.png"
        subprocess.run(["inkscape", str(s), "-o", str(png), "-w", str(ICON_PX * 4), "-h", str(ICON_PX * 4),
                        "--export-background=#000000", "--export-background-opacity=1"], check=True, capture_output=True)
        im = Image.open(png).convert("L").resize((ICON_PX, ICON_PX), Image.LANCZOS)
    return bytes(im.getdata())

def emit_font(out, name, px, chars):
    gl, height, asc = glyphs(px, chars)
    data = bytearray(); rows = []
    for w, h, x0, y0, adv, d in gl:
        rows.append((len(data), w, h, x0, y0, adv)); data += d
    out.append(f"static const uint8_t {name}_DATA[{len(data)}] = {{")
    for i in range(0, len(data), 32):
        out.append("  " + ",".join(str(v) for v in data[i:i + 32]) + ",")
    out.append("};")
    out.append(f"static const Glyph {name}_GLYPHS[{len(rows)}] = {{")
    for r in rows:
        out.append("  {%d,%d,%d,%d,%d,%d}," % (r[0], r[1], r[2], r[3], r[4], r[5]))
    out.append("};")
    out.append(f"constexpr Font {name} = {{ {FIRST}, {LAST}, {height}, {asc}, {name}_GLYPHS, {name}_DATA }};")

def main():
    out = ["// Generated by tools/gen_display_assets.py: do not edit.",
           "// Fonts (DejaVu Sans Bold) and icons (Lucide, ISC licence) of the 160x80 screen, as 8-bit coverage masks.",
           "#pragma once", "#include <cstdint>", "namespace firenet { namespace screen {",
           "struct Glyph { uint16_t off; uint8_t w, h; int8_t x, y; uint8_t adv; };",
           "struct Font { uint8_t first, last, height, ascent; const Glyph* glyphs; const uint8_t* data; };",
           f"constexpr int ICON_SIZE = {ICON_PX};"]
    # Glyph rows are written as {off,w,h,x,y,adv}
    emit_font(out, "FONT_BIG", BIG_PX, BIG_CHARS)
    emit_font(out, "FONT_MEDIUM", MED_PX, None)
    emit_font(out, "FONT_ADDRESS", ADDR_PX, set("0123456789.:"))
    emit_font(out, "FONT_SMALL", SMALL_PX, None)
    names = []
    for n in ICONS:
        m = icon_mask(n); ident = "ICON_" + n.upper().replace("-", "_"); names.append(ident)
        out.append(f"static const uint8_t {ident}[{len(m)}] = {{")
        for i in range(0, len(m), 34):
            out.append("  " + ",".join(str(v) for v in m[i:i + 34]) + ",")
        out.append("};")
    out.append("}}  // namespace firenet::screen")
    (ROOT / "open-firenet" / "firenet_display_assets.h").write_text("\n".join(out) + "\n")

main()
